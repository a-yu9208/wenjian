"""
Gunicorn 生产部署配置 - boke 项目

本文件定义 Gunicorn WSGI 服务器的运行参数，用于生产环境部署。
启动命令：gunicorn -c gunicorn_config.py config.wsgi:application

联动模块：
- config.wsgi: Gunicorn 加载的 WSGI 应用入口
- config.settings: Django 项目配置（通过 wsgi.py 间接引用）
- Nginx: 反向代理到本配置绑定的 127.0.0.1:8000 端口
"""
import multiprocessing

# ============================================================
# 网络绑定
# ============================================================

bind = "127.0.0.1:8000"  # 仅监听本地，由 Nginx 反向代理对外暴露

# ============================================================
# Worker 进程配置
# ============================================================

workers = multiprocessing.cpu_count() * 2 + 1  # 推荐公式：CPU 核心数 × 2 + 1
worker_class = "gthread"  # 线程 Worker，适合 IO 密集型场景（文件上传/数据库查询）
threads = 4  # 每个 Worker 的线程数

# ============================================================
# 超时设置（大文件上传场景需要较长超时）
# ============================================================

timeout = 1800           # 请求超时 30 分钟，匹配 files/videos 大文件上传需求
graceful_timeout = 1800  # 优雅关闭等待时间，与 timeout 保持一致
keepalive = 5            # Keep-Alive 连接等待下一个请求的秒数

# ============================================================
# 连接与请求限制
# ============================================================

worker_connections = 1000    # 每个 Worker 最大并发连接数
max_requests = 1000          # Worker 处理指定请求数后自动重启（防内存泄漏）
max_requests_jitter = 100    # 重启请求数随机偏移，避免所有 Worker 同时重启
backlog = 2048               # 等待连接队列长度

# ============================================================
# 日志配置
# ============================================================

accesslog = 'logs/gunicorn-access.log'  # 访问日志路径
errorlog = 'logs/gunicorn-error.log'    # 错误日志路径
loglevel = 'info'                       # 日志级别

# ============================================================
# 进程管理
# ============================================================

proc_name = 'boke'       # 进程名称，便于 ps/top 中识别
preload_app = True        # 预加载应用代码，减少 Worker fork 后的启动时间
chdir = '/root/.openclaw/workspace/boke'  # 工作目录，确保相对路径正确
